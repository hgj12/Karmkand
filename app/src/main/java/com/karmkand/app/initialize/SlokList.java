package com.karmkand.app.initialize;


public class SlokList {

	private String  header;
	private String slok_name;
	private String slok;

	public void setHeader(String header) {
		this.header = header;
	}

	public String getHeader() {
		return header;
	}

	public String getSlok_name() {
		return slok_name;
	}
	public void setSlok_name(String slok_name) {
		this.slok_name = slok_name;
	}
	public String getSlok() {
		return slok;
	}
	public void setSlok(String slok) {
		this.slok = slok;
	}

}
